describe("ketchup-plan-format", () => {
  const helpers: Tier0Helpers = {
    readStagedFile: () => null,
  };

  test("ACK when ketchup-plan.md not in files", () => {
    const c = ctx({ files: ["src/a.ts"] });
    expect(result(["ketchup-plan-format"], c, helpers).byName.get("ketchup-plan-format")?.decision).toBe("ACK");
  });

  test("NACK on missing TODO section (stub returns content)", () => {
    const h: Tier0Helpers = {
      readStagedFile: () => "# plan\n## DONE\n- x\n",
    };
    const c = ctx({ files: ["ketchup-plan.md"] });
    expect(result(["ketchup-plan-format"], c, h).byName.get("ketchup-plan-format")?.decision).toBe("NACK");
  });

  test("ACK on well-formed plan (stub returns content)", () => {
    const h: Tier0Helpers = {
      readStagedFile: () => "# plan\n## TODO\n- [ ] Burst one [depends: none]\n## DONE\n- [x] Burst zero [depends: none]\n",
    };
    const c = ctx({ files: ["ketchup-plan.md"] });
    expect(result(["ketchup-plan-format"], c, h).byName.get("ketchup-plan-format")?.decision).toBe("ACK");
  });
});

