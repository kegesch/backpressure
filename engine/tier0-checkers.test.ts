import { describe, expect, test } from "bun:test";
import {
  parseDiffAddedLines,
  runTier0Checkers,
  createDefaultHelpers,
  type Tier0Helpers,
} from "./tier0-checkers.ts";
import type { CommitContext } from "./commit-validators.ts";

const ctx = (over: Partial<CommitContext> = {}): CommitContext => ({
  diff: "",
  files: [],
  message: "",
  command: "git commit -m \"x\"",
  cwd: "/tmp",
  ...over,
});

function result(names: string[], context: CommitContext, helpers?: Tier0Helpers) {
  const out = runTier0Checkers(names, context, helpers);
  const byName = new Map(out.map((r) => [r.validator, r]));
  return { out, byName };
}

describe("parseDiffAddedLines", () => {
  test("multi-file buckets", () => {
    const diff = `diff --git a/a.ts b/a.ts
--- a/a.ts
+++ b/a.ts
@@ -1 +1,2 @@
+lineA1
+lineA2
diff --git a/b.ts b/b.ts
--- a/b.ts
+++ b/b.ts
@@ -1 +1 @@
+lineB1
`;
    const m = parseDiffAddedLines(diff);
    expect([...m.keys()]).toEqual(["a.ts", "b.ts"]);
    expect(m.get("a.ts")).toEqual(["lineA1", "lineA2"]);
    expect(m.get("b.ts")).toEqual(["lineB1"]);
  });

  test("/dev/null deletion yields no bucket", () => {
    const diff = `diff --git a/gone.ts b/gone.ts
--- a/gone.ts
+++ /dev/null
@@ -1,2 +0,0 @@
-old1
-old2
`;
    expect([...parseDiffAddedLines(diff).keys()]).toEqual([]);
  });

  test("+++ / --- header lines not treated as added content", () => {
    const diff = `diff --git a/x.ts b/x.ts
--- a/x.ts
+++ b/x.ts
@@ -1 +1,2 @@
+real
`;
    const m = parseDiffAddedLines(diff);
    expect(m.get("x.ts")).toEqual(["real"]);
  });
});

describe("no-dangerous-git", () => {
  test("NACK on --no-verify", () => {
    const c = ctx({ command: "git commit --no-verify -m x" });
    expect(result(["no-dangerous-git"], c).byName.get("no-dangerous-git")).toEqual({
      validator: "no-dangerous-git",
      decision: "NACK",
      reason: expect.stringContaining("--no-verify"),
    });
  });

  test("ACK on safe commit", () => {
    const c = ctx({ command: "git commit -m ok" });
    expect(result(["no-dangerous-git"], c).byName.get("no-dangerous-git")?.decision).toBe("ACK");
  });
});

